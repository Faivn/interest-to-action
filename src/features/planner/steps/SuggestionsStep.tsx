import { useEffect, useState } from 'react';
import { AnimatePresence, m } from 'motion/react';
import { ChevronLeft } from 'lucide-react';
import { Button } from '../../../components/Button';
import { EmptyState } from '../../../components/EmptyState';
import { IconButton } from '../../../components/IconButton';
import { InlineMessage } from '../../../components/InlineMessage';
import { Screen, TopBar } from '../../../components/Screen';
import { SparkMark } from '../../../components/SparkMark';
import { StepIndicator } from '../../../components/StepIndicator';
import { SPRING_SWAP, SWAP_VARIANTS } from '../../../lib/motion';
import type { ContextFields } from '../plannerState';
import { InterestEcho } from '../InterestEcho';
import { PlanRecommendationCard } from '../PlanCard';
import { PlanCardSkeleton } from '../PlanCardSkeleton';
import type { Planner, PlanSuggestion } from '../types';
import './steps.css';

interface SuggestionsStepProps {
  interest: string;
  context: ContextFields;
  suggestions: PlanSuggestion[];
  request: 'idle' | 'loading' | 'error';
  source: Planner['source'];
  savingId: string | null;
  savedId: string | null;
  promote: { id: string; nonce: number } | null;
  saveFailed: boolean;
  onBack: () => void;
  onEditDetails: () => void;
  onRetry: () => void;
  onRegenerate: () => void;
  onSave: (suggestion: PlanSuggestion) => void;
  onEdit: (suggestion: PlanSuggestion) => void;
  onDismiss: (suggestion: PlanSuggestion) => void;
  onNoneOfThese: () => void;
}

/** docs/design.md §4.5 */
export function SuggestionsStep(props: SuggestionsStepProps) {
  const { interest, suggestions, request, source, savingId, savedId, saveFailed } = props;
  const loading = request === 'loading';
  const firstLoad = loading && suggestions.length === 0;
  const regenerating = loading && suggestions.length > 0;
  const locked = savingId !== null || savedId !== null;

  return (
    <Screen
      wash
      topBar={
        <TopBar
          leading={<IconButton label="Back to context" icon={<ChevronLeft />} onClick={props.onBack} />}
          center={<StepIndicator current={3} total={3} />}
        />
      }
    >
      <header className="step-header">
        <h1 className="t-title-1">Here are a few ways to start</h1>
        <p className="t-callout step-lede">Pick one to save, change it to fit your day, or dismiss what doesn't suit you.</p>
      </header>
      <InterestEcho interest={interest} onEdit={props.onEditDetails} />

      {saveFailed && (
        <InlineMessage tone="error">We couldn't save your plan. Nothing has been lost, so you can try saving again.</InlineMessage>
      )}

      {request === 'error' ? (
        <InlineMessage
          tone="error"
          action={
            <div className="inline-actions">
              <Button variant="text" onClick={props.onRetry}>
                Try again
              </Button>
              <Button variant="text" onClick={props.onEditDetails}>
                Edit details
              </Button>
            </div>
          }
        >
          We couldn't get suggestions right now. Your interest is saved on this screen.
        </InlineMessage>
      ) : firstLoad ? (
        <GeneratingState context={props.context} />
      ) : suggestions.length === 0 ? (
        <EmptyState title="No suggestions left" ghostRows={0}>
          Try different ideas, adjust your details, or leave without saving.
        </EmptyState>
      ) : (
        <section
          className={`suggestions${regenerating ? ' suggestions--regenerating' : ''}`}
          aria-label="Suggested plans"
          aria-busy={regenerating || undefined}
        >
          {regenerating && (
            <span className="visually-hidden" role="status">
              Finding different ideas…
            </span>
          )}
          <PlanRecommendationCard
            suggestions={suggestions}
            busy={loading}
            savingId={savingId}
            savedId={savedId}
            promote={props.promote}
            onSave={props.onSave}
            onEdit={props.onEdit}
            onDismiss={props.onDismiss}
          />
        </section>
      )}

      {request !== 'error' && !firstLoad && (
        <div className="suggestions__more">
          <Button
            variant="ai"
            icon={<SparkMark size={18} />}
            loading={regenerating}
            disabled={loading || locked}
            onClick={props.onRegenerate}
          >
            Show different ideas
          </Button>
          <Button variant="text" onClick={props.onNoneOfThese} disabled={locked}>
            None of these
          </Button>
        </div>
      )}

      <InlineMessage>
        {source === 'demo'
          ? "These suggestions come from a built-in demo planner, not a live AI model. They're starting points: save, edit, or dismiss any of them."
          : 'Suggestions are generated by AI and can be wrong. Save, edit, or dismiss any of them.'}
      </InlineMessage>
    </Screen>
  );
}

/**
 * Status lines describe only what the planner is actually given (beUI Reasoning Text, used
 * honestly): nothing is claimed about the user that they didn't say.
 */
function generatingPhrases(context: ContextFields): string[] {
  const phrases = ['Reading your interest…'];
  if (context.timeMinutes) phrases.push(context.timeMinutes === 30 ? 'Keeping it to around half an hour…' : `Fitting it into ${context.timeMinutes} minutes…`);
  if (context.obstacle.trim()) phrases.push('Working around what’s in the way…');
  if (context.outcome.trim()) phrases.push('Connecting it to what success looks like…');
  phrases.push('Finding a few small ways to start…');
  return phrases;
}

const PHRASE_INTERVAL_MS = 1800;

function GeneratingState({ context }: { context: ContextFields }) {
  const [phrases] = useState(() => generatingPhrases(context));
  const [index, setIndex] = useState(0);
  const [slow, setSlow] = useState(false);

  useEffect(() => {
    // Step through the phrases once, then rest on the last one.
    if (index >= phrases.length - 1) return;
    const t = window.setTimeout(() => setIndex((i) => i + 1), PHRASE_INTERVAL_MS);
    return () => window.clearTimeout(t);
  }, [index, phrases.length]);

  useEffect(() => {
    const t = window.setTimeout(() => setSlow(true), 8000);
    return () => window.clearTimeout(t);
  }, []);

  const phrase = slow ? 'Still working on it. Thanks for waiting.' : phrases[index];

  return (
    <section className="generating" aria-busy="true" aria-label="Suggested plans">
      {/* One steady announcement; the rotating phrases are visual only (DESIGN.md §10.1). */}
      <p className="visually-hidden" role="status">
        Generating suggestions.
      </p>
      <p className="generating__caption t-callout" aria-hidden="true">
        <SparkMark size={16} className="generating__spark" />
        <span className="generating__phrase">
          <AnimatePresence mode="wait" initial={false}>
            <m.span
              key={phrase}
              className="text-shimmer"
              variants={SWAP_VARIANTS}
              initial="initial"
              animate="animate"
              exit="exit"
              transition={SPRING_SWAP}
            >
              {phrase}
            </m.span>
          </AnimatePresence>
        </span>
      </p>
      <PlanCardSkeleton />
    </section>
  );
}
